export function money(value) {
  return value.toLocaleString("en-US", { style: "currency", currency: "USD" });
}

export function percentOff(product) {
  if (!product.compareAt || product.compareAt <= product.price) return 0;
  return Math.round(((product.compareAt - product.price) / product.compareAt) * 100);
}

export function getProduct(slug) {
  return products.find((product) => product.slug === slug);
}

export function searchProducts(query) {
  const needle = query.trim().toLowerCase();
  if (!needle) return products;
  return products.filter((product) => {
    const haystack = [
      product.name,
      product.range,
      product.color,
      product.sku,
      product.id,
      product.milk,
      product.description,
      ...product.features,
      ...product.highlights,
    ]
      .join(" ")
      .toLowerCase();
    return haystack.includes(needle);
  });
}

export function relatedProducts(product, limit = 4) {
  const same = products.filter((item) => item.range === product.range && item.slug !== product.slug);
  const rest = products.filter((item) => item.range !== product.range && item.slug !== product.slug);
  return [...same, ...rest].slice(0, limit);
}

export function cartLines(cart) {
  return cart
    .map((line) => {
      const product = getProduct(line.slug);
      if (!product) return null;
      return { ...line, product, lineTotal: product.price * line.qty };
    })
    .filter(Boolean);
}

export function priceCart(cart, promoCode) {
  const lines = cartLines(cart);
  const subtotal = lines.reduce((sum, line) => sum + line.lineTotal, 0);
  const code = (promoCode || "").trim().toUpperCase();
  const discount = code === "VELA10" ? subtotal * 0.1 : 0;
  const shipping = subtotal === 0 || subtotal - discount >= 75 ? 0 : 12;
  const tax = (subtotal - discount) * 0.08;
  const total = subtotal - discount + shipping + tax;
  return { lines, subtotal, discount, shipping, tax, total, code: discount ? code : "" };
}
